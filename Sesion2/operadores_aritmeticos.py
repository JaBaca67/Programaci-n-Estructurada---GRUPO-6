#Operadores aritmeticos
#Leer 2 numeros y caclcular: la suma, resta, multiplicacion, division y comprobar si el primer numero es multiplo del segundo
number1 = int(input("Ingresa un numero: "))
number2 = int(input("Ingresa otro numero: "))

print(f"{number1} + {number2} = {number1 + number2}")
print(f"{number1} - {number2} = {number1 - number2}")
print(f"{number1} x {number2} = {number1 * number2}")
print(f"{number1} / {number2} = {number1 / number2}")
print(f"{number1} % {number2} = {number1 % number2}")


    
